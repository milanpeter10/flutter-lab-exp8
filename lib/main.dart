import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';

import 'book_search_screen.dart';
import 'firebase_options.dart';

// Palette: espresso leather, parchment pages, brass details
const Color kEspresso = Color(0xFF1F2A44);
const Color kParchment = Color(0xFFF5EBD7);
const Color kBrass = Color(0xFF8E2C48);
const Color kPaper = Color(0xFFFFFAF0);
const Color kMuted = Color(0xFF8B7766);

Future<void> main() async {
  // Required before calling native code (Firebase) ahead of runApp().
  WidgetsFlutterBinding.ensureInitialized();

  // Reuses the Experiment 7 Firebase project. Options generated by
  // `flutterfire configure` (lib/firebase_options.dart) for Android and Web.
  // Android also uses android/app/google-services.json.
  Object? initError;
  try {
    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );
  } catch (e) {
    initError = e;
  }

  runApp(LibraryApp(initError: initError));
}

class LibraryApp extends StatelessWidget {
  const LibraryApp({super.key, this.initError});

  /// Non-null when Firebase failed to initialize.
  final Object? initError;

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Library Book Search',
      debugShowCheckedModeBanner: false,
      theme: ThemeData(
        colorScheme: ColorScheme.fromSeed(seedColor: kBrass),
        scaffoldBackgroundColor: kParchment,
        appBarTheme: const AppBarTheme(
          backgroundColor: kEspresso,
          foregroundColor: Colors.white,
          centerTitle: true,
          elevation: 0,
        ),
        useMaterial3: true,
      ),
      home: initError == null
          ? const BookSearchScreen()
          : _FirebaseErrorScreen(error: initError!),
    );
  }
}

/// Shown instead of the search screen when Firebase could not start,
/// so the problem is visible rather than a blank or crashing app.
class _FirebaseErrorScreen extends StatelessWidget {
  const _FirebaseErrorScreen({required this.error});

  final Object error;

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Library Book Search')),
      body: Center(
        child: Padding(
          padding: const EdgeInsets.all(24),
          child: Text(
            'Firebase initialization failed.\n\n'
            'Check lib/firebase_options.dart (run `flutterfire configure`) '
            'and android/app/google-services.json.\n\nError: $error',
            textAlign: TextAlign.center,
            style: const TextStyle(color: Colors.red),
          ),
        ),
      ),
    );
  }
}
